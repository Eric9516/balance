export async function seedRubrosBase(prisma: PrismaClient): Promise<void> {
  console.log('Borrando rubros existentes...')
  await prisma.rubroBase.deleteMany({})

  console.log(`Insertando ${RUBROS_BASE.length} rubros base...`)
  for (const rubro of RUBROS_BASE) {
    await prisma.rubroBase.create({ data: rubro })
  }

  console.log('Rubros base insertados correctamente.')
}


